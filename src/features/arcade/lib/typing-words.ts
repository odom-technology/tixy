/**
 * Simple seeded PRNG (mulberry32).
 * Produces deterministic pseudo-random numbers from a 32-bit seed.
 */
function seededRandom(seed: number): () => number {
  let s = seed | 0;
  return () => {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Generate a deterministic word list from a seed.
 * Produces the same words on client and server for the same seed.
 */
export function generateSeededWords(seed: number, count: number = 200): string[] {
  const rng = seededRandom(seed);
  const result: string[] = [];
  let lastWord = '';
  for (let i = 0; i < count; i++) {
    let word = ENGLISH_WORDS[Math.floor(rng() * ENGLISH_WORDS.length)];
    while (word === lastWord && ENGLISH_WORDS.length > 1) {
      word = ENGLISH_WORDS[Math.floor(rng() * ENGLISH_WORDS.length)];
    }
    result.push(word);
    lastWord = word;
  }
  return result;
}
