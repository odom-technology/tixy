/** O(1) membership set built once at module load. */
export const DICTIONARY: Set<string> = new Set(DICTIONARY_WORDS);

/** Per-word score: 4-letter word = 1pt; 5+ letters = 1pt/letter; pangram = +7. */
export function scorePangramWord(word: string): number {
  const len = word.length;
  let pts = len === 4 ? 1 : len;
  if (new Set(word).size === 7) pts += 7;
  return pts;
}

export type PangramSolutions = {
  /** Every valid word for the set, sorted. */
  words: string[];
  /** The subset that uses all 7 letters. */
  pangrams: string[];
  /** Sum of scorePangramWord over every valid word. */
  maxScore: number;
};

/**
 * Compute the full solution set for a letter set against the DICTIONARY.
 * Pure + deterministic. Server-only.
 */
export function solutionsFor(set: PangramSet): PangramSolutions {
  const letterSet = new Set(set.letters);
  const words: string[] = [];
  const pangrams: string[] = [];
  let maxScore = 0;
  for (const word of DICTIONARY) {
    if (word.length < 4) continue;
    if (!word.includes(set.center)) continue;
    let ok = true;
    for (let i = 0; i < word.length; i++) {
      if (!letterSet.has(word[i]!)) {
        ok = false;
        break;
      }
    }
    if (!ok) continue;
    words.push(word);
    maxScore += scorePangramWord(word);
    if (new Set(word).size === 7) pangrams.push(word);
  }
  words.sort();
  pangrams.sort();
  return { words, pangrams, maxScore };
}
